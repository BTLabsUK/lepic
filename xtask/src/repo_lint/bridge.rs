//! The Rust half of the flutter_rust_bridge bindings, `crates/lepic-ffi/src/frb_generated.rs`, is
//! generated together with the Dart half in the binding's own repository, from the API in
//! `crates/lepic-ffi/src/api`. That run records the SHA-256 of every API file and of the generated
//! module in `crates/lepic-ffi/bridge.sha256`, in `sha256sum` format with paths relative to the
//! crate. This gate fails when any of them changed since, so the API cannot change without both
//! halves being generated again, and when the module comes from another flutter_rust_bridge
//! version than the one `Cargo.lock` resolves.

use std::collections::BTreeMap;
use std::fmt;

use sha2::{Digest, Sha256};

use crate::sources::SourceFile;

pub(crate) const CRATE_DIR: &str = "crates/lepic-ffi";
pub(crate) const API_DIR: &str = "crates/lepic-ffi/src/api";
pub(crate) const GENERATED_FILE: &str = "crates/lepic-ffi/src/frb_generated.rs";
pub(crate) const MANIFEST_FILE: &str = "crates/lepic-ffi/bridge.sha256";
const BRIDGE_PACKAGE: &str = "flutter_rust_bridge";
const VERSION_ITEM: &str = "FLUTTER_RUST_BRIDGE_CODEGEN_VERSION: &str = \"";
const REGENERATE: &str = "generate the bindings again with `tool/lepic.sh generate` in the \
                          binding repository, gitlab.com/bt-labs-group/lepic-flutter";

#[derive(Debug, PartialEq, Eq)]
pub(crate) enum Violation {
    ManifestMissing,
    Malformed { line: usize },
    Changed { file: String },
    Unrecorded { file: String },
    Missing { file: String },
    VersionUnknown,
    VersionMismatch { generated: String, locked: String },
}

impl fmt::Display for Violation {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::ManifestMissing => write!(f, "{MANIFEST_FILE} is missing; {REGENERATE}"),
            Self::Malformed { line } => write!(
                f,
                "{MANIFEST_FILE}:{line}: expected `<sha256>  <path>`; {REGENERATE}"
            ),
            Self::Changed { file } => write!(
                f,
                "{CRATE_DIR}/{file} changed since the bindings were generated; {REGENERATE}"
            ),
            Self::Unrecorded { file } => write!(
                f,
                "{CRATE_DIR}/{file} is not in {MANIFEST_FILE}; {REGENERATE}"
            ),
            Self::Missing { file } => write!(
                f,
                "{MANIFEST_FILE} lists {file}, which does not exist; {REGENERATE}"
            ),
            Self::VersionUnknown => write!(
                f,
                "could not read the {BRIDGE_PACKAGE} version of {GENERATED_FILE} or Cargo.lock"
            ),
            Self::VersionMismatch { generated, locked } => write!(
                f,
                "{GENERATED_FILE} was generated by {BRIDGE_PACKAGE} {generated}, Cargo.lock \
                 resolves {locked}; {REGENERATE}"
            ),
        }
    }
}

/// `api` holds the files under `API_DIR` and `generated` the module, both with root-relative
/// paths; `manifest` is the text of `MANIFEST_FILE`, `None` when it does not exist.
pub(crate) fn check(
    api: &[SourceFile],
    generated: Option<&SourceFile>,
    manifest: Option<&str>,
    lockfile: &str,
) -> Vec<Violation> {
    let mut violations = Vec::new();
    let generated_version = generated.and_then(|file| codegen_version(&file.text));
    match (generated_version, locked_version(lockfile)) {
        (Some(generated), Some(locked)) if generated != locked => {
            violations.push(Violation::VersionMismatch {
                generated: generated.to_owned(),
                locked: locked.to_owned(),
            });
        }
        (Some(_), Some(_)) => {}
        _ => violations.push(Violation::VersionUnknown),
    }

    let Some(manifest) = manifest else {
        violations.push(Violation::ManifestMissing);
        return violations;
    };
    let mut recorded = BTreeMap::new();
    for (index, line) in manifest.lines().enumerate() {
        match parse_entry(line) {
            Some((digest, path)) => {
                recorded.insert(path, digest);
            }
            None => violations.push(Violation::Malformed {
                line: index.saturating_add(1),
            }),
        }
    }

    let prefix = format!("{CRATE_DIR}/");
    for file in api.iter().chain(generated) {
        let Some(path) = file.path.strip_prefix(&prefix) else {
            continue;
        };
        match recorded.remove(path) {
            Some(digest) if digest == sha256_hex(&file.text) => {}
            Some(_) => violations.push(Violation::Changed {
                file: path.to_owned(),
            }),
            None => violations.push(Violation::Unrecorded {
                file: path.to_owned(),
            }),
        }
    }
    violations.extend(recorded.into_keys().map(|file| Violation::Missing {
        file: file.to_owned(),
    }));
    violations
}

/// `(sha256, path)` of one `sha256sum` line: 64 lowercase hex digits, a space, a space or `*`,
/// and the path.
fn parse_entry(line: &str) -> Option<(&str, &str)> {
    let digest = line.get(..64)?;
    let path = line
        .get(64..)?
        .strip_prefix("  ")
        .or_else(|| line.get(64..)?.strip_prefix(" *"))?;
    let hex = digest
        .chars()
        .all(|c| c.is_ascii_digit() || ('a'..='f').contains(&c));
    (hex && !path.is_empty()).then_some((digest, path))
}

fn sha256_hex(text: &str) -> String {
    Sha256::digest(text.as_bytes())
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// The version the generated module records in `FLUTTER_RUST_BRIDGE_CODEGEN_VERSION`.
fn codegen_version(generated: &str) -> Option<&str> {
    let start = generated
        .find(VERSION_ITEM)?
        .checked_add(VERSION_ITEM.len())?;
    let rest = generated.get(start..)?;
    rest.get(..rest.find('"')?)
}

/// The version of the `flutter_rust_bridge` package in `Cargo.lock`. Cargo writes one
/// `key = "value"` per line, `name` before `version`.
fn locked_version(lockfile: &str) -> Option<&str> {
    let mut in_bridge = false;
    for line in lockfile.lines().map(str::trim) {
        if line == "[[package]]" {
            in_bridge = false;
        } else if let Some(name) = quoted_value(line, "name") {
            in_bridge = name == BRIDGE_PACKAGE;
        } else if in_bridge && let Some(version) = quoted_value(line, "version") {
            return Some(version);
        }
    }
    None
}

fn quoted_value<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    line.strip_prefix(key)?
        .trim_start()
        .strip_prefix('=')?
        .trim()
        .strip_prefix('"')?
        .strip_suffix('"')
}

#[cfg(test)]
mod tests {
    use super::*;

    const LOCK: &str = "[[package]]\nname = \"flutter_rust_bridge\"\nversion = \"2.13.0\"\n\n\
                        [[package]]\nname = \"flutter_rust_bridge_macros\"\nversion = \"2.14.0\"\n";

    fn source(path: &str, text: &str) -> SourceFile {
        SourceFile {
            path: path.to_owned(),
            text: text.to_owned(),
        }
    }

    fn generated(version: &str) -> SourceFile {
        source(
            GENERATED_FILE,
            &format!(
                "pub(crate) const FLUTTER_RUST_BRIDGE_CODEGEN_VERSION: &str = \"{version}\";\n"
            ),
        )
    }

    fn manifest(files: &[&SourceFile]) -> String {
        files
            .iter()
            .map(|file| {
                let path = file.path.strip_prefix("crates/lepic-ffi/").unwrap();
                format!("{}  {path}\n", sha256_hex(&file.text))
            })
            .collect()
    }

    #[test]
    fn accepts_the_files_as_generated() {
        let api = [
            source("crates/lepic-ffi/src/api/mod.rs", "pub mod wallet;\n"),
            source("crates/lepic-ffi/src/api/wallet.rs", "pub fn open() {}\n"),
        ];
        let generated = generated("2.13.0");
        let recorded = manifest(&[&api[0], &api[1], &generated]);
        assert_eq!(check(&api, Some(&generated), Some(&recorded), LOCK), vec![]);
    }

    #[test]
    fn rejects_a_changed_new_or_removed_api_file() {
        let wallet = source("crates/lepic-ffi/src/api/wallet.rs", "pub fn open() {}\n");
        let gone = source("crates/lepic-ffi/src/api/gone.rs", "\n");
        let generated = generated("2.13.0");
        let recorded = manifest(&[&wallet, &gone, &generated]);
        let api = [
            source("crates/lepic-ffi/src/api/new.rs", "pub fn new() {}\n"),
            source(
                "crates/lepic-ffi/src/api/wallet.rs",
                "pub fn open(x: u8) {}\n",
            ),
        ];
        assert_eq!(
            check(&api, Some(&generated), Some(&recorded), LOCK),
            vec![
                Violation::Unrecorded {
                    file: "src/api/new.rs".to_owned()
                },
                Violation::Changed {
                    file: "src/api/wallet.rs".to_owned()
                },
                Violation::Missing {
                    file: "src/api/gone.rs".to_owned()
                },
            ]
        );
    }

    #[test]
    fn rejects_an_edited_generated_module() {
        let generated = generated("2.13.0");
        let recorded = manifest(&[&generated]);
        let mut edited = generated;
        edited.text.push_str("// by hand\n");
        assert_eq!(
            check(&[], Some(&edited), Some(&recorded), LOCK),
            vec![Violation::Changed {
                file: "src/frb_generated.rs".to_owned()
            }]
        );
    }

    #[test]
    fn rejects_another_codegen_version_than_the_locked_one() {
        let generated = generated("2.12.0");
        let recorded = manifest(&[&generated]);
        assert_eq!(
            check(&[], Some(&generated), Some(&recorded), LOCK),
            vec![Violation::VersionMismatch {
                generated: "2.12.0".to_owned(),
                locked: "2.13.0".to_owned()
            }]
        );
        assert_eq!(
            check(&[], None, Some(""), LOCK),
            vec![Violation::VersionUnknown]
        );
    }

    #[test]
    fn rejects_a_missing_or_malformed_manifest() {
        let generated = generated("2.13.0");
        assert_eq!(
            check(&[], Some(&generated), None, LOCK),
            vec![Violation::ManifestMissing]
        );
        let recorded = format!("{}not a line\n", manifest(&[&generated]));
        assert_eq!(
            check(&[], Some(&generated), Some(&recorded), LOCK),
            vec![Violation::Malformed { line: 2 }]
        );
    }

    #[test]
    fn reads_both_sha256sum_line_forms() {
        let digest = "a".repeat(64);
        assert_eq!(
            parse_entry(&format!("{digest}  src/api/mod.rs")),
            Some((digest.as_str(), "src/api/mod.rs"))
        );
        assert_eq!(
            parse_entry(&format!("{digest} *src/api/mod.rs")),
            Some((digest.as_str(), "src/api/mod.rs"))
        );
        assert_eq!(
            parse_entry(&format!("{} src/api/mod.rs", "A".repeat(64))),
            None
        );
        assert_eq!(parse_entry("short  src/api/mod.rs"), None);
    }
}
